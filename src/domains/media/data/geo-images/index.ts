GEO_IMAGES.forEach((img) => (IMAGE_SLUGS[img.slug] = img));

// Funciones de acceso
export const getAllImages = (): OptimizedCloudinaryImage[] => GEO_IMAGES;
export const getImageById = (
  id: string,
): OptimizedCloudinaryImage | undefined => IMAGE_MAP[id];
export const getImageBySlug = (
  slug: string,
): OptimizedCloudinaryImage | undefined => IMAGE_SLUGS[slug];

// Helper para URLs optimizadas
export const getOptimizedUrl = (
  imageId: string,
  options: {
    width?: number;
    height?: number;
    quality?: string;
    format?: string;
  } = {},
): string => {
  const image = getImageById(imageId);
  if (!image) return "";

  const {
    width = 800,
    height = 600,
    quality = "auto",
    format = "webp",
  } = options;
  const baseUrl = image.cloudinary.secure_url.replace(
    "/upload/",
    `/upload/w_${width},h_${height},c_fill,q_${quality},f_${format}/`,
  );
  return baseUrl;
};
